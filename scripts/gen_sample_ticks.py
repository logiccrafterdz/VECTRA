#!/usr/bin/env python3
"""Generate the synthetic sample tick dataset used by VECTRA smoke tests.

IMPORTANT: this data is SYNTHETIC. It exists to exercise the pipeline
(validation, features, scoring, risk, execution, reporting) and to make
edge-case paths reachable (wide spreads, malformed rows, duplicates,
out-of-order timestamps, a stale gap, a flat zero-volatility stretch).
It is NOT evidence of a trading edge and must never be presented as such.

Output: examples/sample_ticks.csv
Columns: symbol,bid,ask,source_ts_ns,sequence

Everything is deterministic for a fixed seed.
"""

import os
import random

SEED = 20261015
N = 6000
START_NS = 1_767_532_800_000_000_000  # 2026-01-05T00:00:00Z
STEP_NS = 100_000_000                # 100 ms per tick
SYMBOL = "EURUSD"

OUT_PATH = os.path.join(os.path.dirname(__file__), os.pardir, "examples", "sample_ticks.csv")


def regime(i):
    """(drift, volatility, spread) per tick index. Random walk = drift + vol * N(0,1)."""
    if i < 800:                       # quiet range
        return 0.0, 2.0e-5, 0.00010
    if i < 1600:                      # strong steady uptrend
        return 6.0e-5, 4.0e-5, 0.00010
    if i < 1800:                      # abrupt momentum flip (exhaustion test)
        return -7.0e-5, 5.0e-5, 0.00012
    if i < 2400:                      # steady downtrend
        return -5.0e-5, 4.0e-5, 0.00010
    if i < 3000:                      # choppy
        return 0.0, 5.0e-5, 0.00011
    if i < 3600:                      # wide-spread episode (validator rejects)
        return 0.0, 3.0e-5, 0.00060
    if i < 4200:                      # perfectly flat: zero volatility
        return 0.0, 0.0, 0.00010
    if i < 4400:                      # elevated but legal spread (risk rejects)
        return 4.0e-5, 4.0e-5, 0.00045
    if i < 5000:                      # recovery uptrend
        return 5.0e-5, 4.0e-5, 0.00010
    if i < 5400:                      # second momentum flip
        return -8.0e-5, 6.0e-5, 0.00013
    return 2.0e-5, 3.0e-5, 0.00010    # mild recovery


def fmt(price):
    # Five decimal places: standard FX quote precision.
    return f"{price:.5f}"


def main():
    rng = random.Random(SEED)
    price = 1.10000
    rows = []

    for i in range(N):
        drift, vol, spread = regime(i)
        if vol <= 0.0:
            pass  # perfectly flat: price unchanged
        else:
            price += drift + vol * rng.gauss(0.0, 1.0)
        price = max(0.5, price)

        half = spread / 2.0
        bid = round(price - half, 5)
        ask = round(price + half, 5)
        if ask <= bid:  # never generate an accidental crossed market
            ask = bid + 0.00001

        ts = START_NS + i * STEP_NS
        rows.append([SYMBOL, fmt(bid), fmt(ask), str(ts), str(i + 1)])

    # ------------------------------------------------------------------
    # Injected data-quality anomalies (deliberate; each one is testable).
    # ------------------------------------------------------------------
    # 1) exact duplicate row (same timestamp and sequence)
    rows[900] = list(rows[899])
    # 2) crossed market: ask < bid
    rows[1500][1], rows[1500][2] = rows[1500][2], rows[1500][1]
    # 3) malformed price
    rows[2000][1] = "not-a-price"
    # 4) unexpected symbol
    rows[2500][0] = "GBPUSD"
    # 5) timestamp 50 ms behind the previous event (out of order)
    rows[3000][3] = str(int(rows[3000][3]) - 50_000_000)
    # 6) repeated sequence number with a fresh timestamp
    rows[4700][4] = rows[4699][4]
    # 7) stale gap: 10 s of silence starting at row 4500
    for r in rows[4500:]:
        r[3] = str(int(r[3]) + 10_000_000_000)

    out_dir = os.path.dirname(os.path.abspath(OUT_PATH))
    os.makedirs(out_dir, exist_ok=True)
    with open(OUT_PATH, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("# VECTRA synthetic sample data - NOT real market data, NOT evidence of an edge\n")
        fh.write("# generated by scripts/gen_sample_ticks.py (deterministic seed)\n")
        fh.write("symbol,bid,ask,source_ts_ns,sequence\n")
        for row in rows:
            fh.write(",".join(row) + "\n")
    print(f"wrote {len(rows)} rows to {os.path.normpath(OUT_PATH)}")


if __name__ == "__main__":
    main()
